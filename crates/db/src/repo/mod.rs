//! Repositories: the only place SQL is written.
//!
//! Every repository takes a `&Db` and returns `jobseeker-core` domain types, so nothing
//! above this layer knows about sqlx or about column names.
//!
//! Rules enforced here (see `docs/09-api.md`):
//!   * no `SELECT *` in list queries — project only what the caller renders;
//!   * child collections are fetched with `WHERE parent_id IN (...)`, never per row;
//!   * filters compose in SQL, never in Rust;
//!   * cursor pagination, never `OFFSET`, on tables that grow.

